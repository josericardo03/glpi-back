-- Sessões com refresh token, recuperação de senha e verificação em duas etapas (TOTP).

-- token_versao: somar 1 invalida na hora todos os tokens de acesso emitidos antes (troca de senha, sair de tudo).
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS token_versao INT NOT NULL DEFAULT 0;
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS senha_alterada_em TIMESTAMPTZ(6);
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS mfa_ativo BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS mfa_segredo VARCHAR(255);
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS mfa_ultimo_passo BIGINT;
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS mfa_codigos_hash TEXT[] NOT NULL DEFAULT '{}';

-- Um registro por dispositivo/navegador conectado. Só o hash do refresh token é guardado.
CREATE TABLE IF NOT EXISTS sessoes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    id_cliente INT NOT NULL,
    id_usuario INT NOT NULL,
    token_hash CHAR(64) NOT NULL,
    token_hash_anterior CHAR(64),
    criado_em TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
    expira_em TIMESTAMPTZ(6) NOT NULL,
    ultimo_uso TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
    revogado_em TIMESTAMPTZ(6),
    endereco_ip VARCHAR(64),
    agente VARCHAR(255),
    CONSTRAINT uq_sessao_token UNIQUE (token_hash),
    CONSTRAINT fk_sessao_usuario FOREIGN KEY (id_cliente, id_usuario)
        REFERENCES usuarios (id_cliente, id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_sessoes_usuario ON sessoes (id_cliente, id_usuario) WHERE revogado_em IS NULL;

CREATE TABLE IF NOT EXISTS tokens_recuperacao (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente INT NOT NULL,
    id_usuario INT NOT NULL,
    token_hash CHAR(64) NOT NULL,
    criado_em TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
    expira_em TIMESTAMPTZ(6) NOT NULL,
    usado_em TIMESTAMPTZ(6),
    CONSTRAINT pk_tokens_recuperacao PRIMARY KEY (id_cliente, id),
    CONSTRAINT uq_token_recuperacao UNIQUE (token_hash),
    CONSTRAINT fk_token_recuperacao_usuario FOREIGN KEY (id_cliente, id_usuario)
        REFERENCES usuarios (id_cliente, id) ON DELETE CASCADE
);
