CREATE EXTENSION IF NOT EXISTS "citext";

CREATE TABLE clientes (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    razao_social VARCHAR(150) NOT NULL,
    nome_fantasia VARCHAR(100) NOT NULL,
    cnpj VARCHAR(18) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    data_contratacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_clientes PRIMARY KEY (id),
    CONSTRAINT uq_clientes_cnpj UNIQUE (cnpj),
    CONSTRAINT ck_cliente_status CHECK (status IN ('ATIVO', 'BLOQUEADO', 'INATIVO'))
);

CREATE TABLE departamentos (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente INT NOT NULL,
    codigo_sigla VARCHAR(20) NOT NULL,
    nome VARCHAR(100) NOT NULL,
    id_responsavel INT,
    id_departamento_pai INT,
    status VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_departamentos PRIMARY KEY (id_cliente, id),
    CONSTRAINT uq_departamentos_id UNIQUE (id),
    CONSTRAINT fk_depto_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id) ON DELETE CASCADE,
    CONSTRAINT fk_depto_pai FOREIGN KEY (id_cliente, id_departamento_pai) REFERENCES departamentos(id_cliente, id) ON DELETE RESTRICT,
    CONSTRAINT uq_sigla_por_cliente UNIQUE (id_cliente, codigo_sigla),
    CONSTRAINT ck_depto_status CHECK (status IN ('ATIVO', 'INATIVO'))
);

CREATE TABLE usuarios (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente INT NOT NULL,
    nome VARCHAR(100) NOT NULL,
    email CITEXT NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    id_departamento INT,
    cargo VARCHAR(100) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    avatar_url VARCHAR(255),
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ultimo_login TIMESTAMPTZ,
    CONSTRAINT pk_usuarios PRIMARY KEY (id_cliente, id),
    CONSTRAINT uq_usuarios_id UNIQUE (id),
    CONSTRAINT uq_email_por_cliente UNIQUE (id_cliente, email),
    CONSTRAINT fk_usuario_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_depto FOREIGN KEY (id_cliente, id_departamento) REFERENCES departamentos(id_cliente, id) ON DELETE RESTRICT,
    CONSTRAINT ck_usuario_status CHECK (status IN ('ATIVO', 'DESATIVADO', 'PENDENTE_CONFIRMACAO')),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMIN', 'GESTOR', 'TECNICO', 'SOLICITANTE'))
);

ALTER TABLE departamentos ADD CONSTRAINT fk_depto_responsavel FOREIGN KEY (id_cliente, id_responsavel) REFERENCES usuarios(id_cliente, id) ON DELETE RESTRICT;

