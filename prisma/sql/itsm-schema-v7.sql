CREATE OR REPLACE FUNCTION fn_check_intervalo_sobreposicao()
RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM intervalos_horarios
        WHERE id_cliente = NEW.id_cliente
          AND id_horario_comercial = NEW.id_horario_comercial
          AND dia_semana = NEW.dia_semana
          AND id <> NEW.id
          AND (
              (NEW.hora_inicio, NEW.hora_fim) OVERLAPS (hora_inicio, hora_fim)
          )
    ) THEN
        RAISE EXCEPTION 'Sobreposição de horário detectada para o dia da semana % no horário comercial %.', NEW.dia_semana, NEW.id_horario_comercial;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_check_intervalo_sobreposicao
BEFORE INSERT OR UPDATE ON intervalos_horarios
FOR EACH ROW EXECUTE FUNCTION fn_check_intervalo_sobreposicao();

CREATE OR REPLACE FUNCTION fn_impedir_alteracao_auditoria()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'A tabela de logs de auditoria é imutável para o usuário da aplicação. Operações de UPDATE, DELETE ou TRUNCATE são estritamente proibidas para conformidade forense.';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_prevent_update_delete_auditoria
BEFORE UPDATE OR DELETE OR TRUNCATE ON logs_auditoria
FOR EACH STATEMENT EXECUTE FUNCTION fn_impedir_alteracao_auditoria();

