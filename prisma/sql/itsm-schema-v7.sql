CREATE TABLE chamados (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente INT NOT NULL,
    id_solicitante INT NOT NULL,
    id_tecnico_atribuido INT,
    id_grupo_responsavel INT,
    id_categoria INT NOT NULL,
    id_politica_sla INT,
    titulo VARCHAR(255) NOT NULL,
    descricao TEXT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    origem VARCHAR(20) NOT NULL DEFAULT 'PORTAL',
    prioridade VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'NOVO',
    data_abertura TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_previsao_resolucao TIMESTAMPTZ,
    data_resolucao TIMESTAMPTZ,
    data_fechamento TIMESTAMPTZ,
    resolucao TEXT,
    tempo_acumulado_pausa_s INT NOT NULL DEFAULT 0,
    sla_vencido BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_chamados PRIMARY KEY (id_cliente, id),
    CONSTRAINT uq_chamados_id UNIQUE (id),
    CONSTRAINT fk_chamado_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id) ON DELETE CASCADE,
    CONSTRAINT fk_chamado_solicitante FOREIGN KEY (id_cliente, id_solicitante) REFERENCES usuarios(id_cliente, id) ON DELETE RESTRICT,
    CONSTRAINT fk_chamado_tecnico FOREIGN KEY (id_cliente, id_tecnico_atribuido) REFERENCES usuarios(id_cliente, id) ON DELETE RESTRICT,
    CONSTRAINT fk_chamado_grupo FOREIGN KEY (id_cliente, id_grupo_responsavel) REFERENCES grupos_suporte(id_cliente, id) ON DELETE RESTRICT,
    CONSTRAINT fk_chamado_categoria FOREIGN KEY (id_cliente, id_categoria) REFERENCES categorias_chamados(id_cliente, id) ON DELETE RESTRICT,
    CONSTRAINT fk_chamado_sla FOREIGN KEY (id_cliente, id_politica_sla) REFERENCES politicas_sla(id_cliente, id) ON DELETE RESTRICT,
    CONSTRAINT ck_chamado_tipo CHECK (tipo IN ('INCIDENTE', 'REQUISICAO')),
    CONSTRAINT ck_chamado_origem CHECK (origem IN ('PORTAL', 'TELEFONE', 'EMAIL', 'CHAT', 'API')),
    CONSTRAINT ck_chamado_prioridade CHECK (prioridade IN ('CRITICA', 'ALTA', 'MEDIA', 'BAIXA')),
    CONSTRAINT ck_chamado_status CHECK (status IN ('NOVO', 'EM_ATENDIMENTO', 'PENDENTE', 'RESOLVIDO', 'CONCLUIDO')),
    CONSTRAINT ck_chamado_tempo_pausa CHECK (tempo_acumulado_pausa_s >= 0),
    CONSTRAINT ck_chamados_datas CHECK (
        (data_resolucao IS NULL OR data_resolucao >= data_abertura) AND
        (data_fechamento IS NULL OR data_fechamento >= data_abertura) AND
        (data_fechamento IS NULL OR data_resolucao IS NOT NULL) AND
        (data_fechamento IS NULL OR data_resolucao IS NULL OR data_fechamento >= data_resolucao)
    )
);

