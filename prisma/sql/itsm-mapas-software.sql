-- Mapas de software: cada dependência (relacionamentos_ativos) passa a pertencer a um mapa nomeado.
CREATE TABLE IF NOT EXISTS mapas_software (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente INT NOT NULL,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(500),
    data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_mapas_software PRIMARY KEY (id_cliente, id),
    CONSTRAINT uq_mapas_software_id UNIQUE (id),
    CONSTRAINT fk_mapa_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_mapas_software_nome ON mapas_software (id_cliente, lower(nome));

ALTER TABLE relacionamentos_ativos ADD COLUMN IF NOT EXISTS id_mapa INT;

-- As dependências que já existem vão para um mapa "Principal" de cada cliente.
INSERT INTO mapas_software (id_cliente, nome, descricao)
SELECT DISTINCT r.id_cliente, 'Principal', 'Criado a partir das dependências que já estavam cadastradas.'
FROM relacionamentos_ativos r
WHERE r.id_mapa IS NULL
ON CONFLICT DO NOTHING;

UPDATE relacionamentos_ativos r
SET id_mapa = m.id
FROM mapas_software m
WHERE r.id_mapa IS NULL
  AND m.id_cliente = r.id_cliente
  AND lower(m.nome) = 'principal';

ALTER TABLE relacionamentos_ativos ALTER COLUMN id_mapa SET NOT NULL;
ALTER TABLE relacionamentos_ativos
    ADD CONSTRAINT fk_ra_mapa FOREIGN KEY (id_cliente, id_mapa)
    REFERENCES mapas_software (id_cliente, id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS idx_rel_ativos_mapa ON relacionamentos_ativos (id_cliente, id_mapa);
