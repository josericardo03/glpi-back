CREATE TABLE IF NOT EXISTS anexos_artigos_kb (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente INT NOT NULL,
    id_artigo INT NOT NULL,
    nome_arquivo VARCHAR(255) NOT NULL,
    caminho_storage VARCHAR(512) NOT NULL,
    tipo_mime VARCHAR(100) NOT NULL,
    tamanho_bytes BIGINT NOT NULL,
    conteudo BYTEA,
    data_upload TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
    CONSTRAINT pk_anexos_artigos_kb PRIMARY KEY (id_cliente, id),
    CONSTRAINT fk_anexo_artigo_kb_artigo FOREIGN KEY (id_cliente, id_artigo) REFERENCES artigos_kb (id_cliente, id) ON DELETE CASCADE,
    CONSTRAINT fk_anexo_artigo_kb_cliente FOREIGN KEY (id_cliente) REFERENCES clientes (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_anexos_artigos_kb_artigo
    ON anexos_artigos_kb (id_cliente, id_artigo);
